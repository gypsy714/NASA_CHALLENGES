import assert from 'node:assert/strict';
import { createMarsMission, commandMars, stepMars, canDeployChute, communicationReady, rocks } from '../src/marsPhysics.js';
import { DEFAULT_MARS_CONFIGURATION, payloadStats, payloadChecks } from '../src/marsConfiguration.js';

function simulateLanding({ parachute = true, engines = true, fuel = 500 } = {}) {
  const s = createMarsMission(); s.phase = 'entry'; s.fuel = fuel;
  assert.equal(commandMars(s, 'chute'), false, 'early deployment must be rejected');
  for (let t = 0; t < 1600 && !['landed', 'failed'].includes(s.phase); t += .05) {
    if (parachute && s.phase === 'entry' && canDeployChute(s)) commandMars(s, 'chute');
    if (engines && s.phase === 'parachute' && s.altitude < 2200) commandMars(s, 'powered');
    stepMars(s, .05);
  }
  return s;
}
const landed = simulateLanding();
assert.equal(landed.phase, 'landed');
assert.ok(landed.fuel > 0 && landed.fuel < 500);
assert.equal(simulateLanding({ engines: false }).phase, 'failed');
assert.equal(simulateLanding({ parachute: false }).phase, 'failed');
assert.equal(simulateLanding({ fuel: 1 }).phase, 'failed');
const manual = createMarsMission();
Object.assign(manual, { phase: 'descent', powered: true, guidance: false, altitude: 400, vertical: -10, horizontal: 0, throttle: 0 });
stepMars(manual, .1); assert.ok(manual.vertical < -10, 'gravity remains active with throttle zero');
const transfer = createMarsMission();
assert.ok(commandMars(transfer, 'burn'));
for (let i = 0; i < 800; i++) stepMars(transfer, .05);
assert.equal(transfer.phase, 'cruise');
assert.ok(transfer.serviceFuel < 520);
transfer.warp = 20; stepMars(transfer, 11);
assert.equal(transfer.phase, 'arrival');
assert.equal(commandMars(transfer, 'entry'), false);
for (let i = 0; i < 8; i++) commandMars(transfer, 'correct', -1);
assert.ok(commandMars(transfer, 'entry'));
commandMars(landed, 'deploy');
for (let i = 0; i < 80; i++) stepMars(landed, .05);
assert.equal(commandMars(landed, 'sample'), false, 'no collection from across the map');
const oldZ = landed.rover.z, oldBattery = landed.rover.battery;
for (let i = 0; i < 100; i++) stepMars(landed, .05, { forward: 1 });
assert.ok(landed.rover.z < oldZ);
assert.ok(landed.rover.battery < oldBattery);
const headingBefore = landed.rover.heading;
stepMars(landed, .1, { steer: 1 });
assert.ok(landed.rover.heading > headingBefore, 'right steering turns toward positive X from north');
for (let i = 0; i < 30; i++) stepMars(landed, .05, { brake: true });
assert.ok(Math.abs(landed.rover.speed) < .01);
const rock = rocks[0];
Object.assign(landed.rover, { x: rock.x, z: rock.z + rock.radius + 1.01, heading: 0, speed: 1 });
stepMars(landed, .05, { forward: 1 }); assert.equal(landed.rover.speed, 0, 'rock collision stops rover');
Object.assign(landed.rover, { x: -9, z: -9, speed: 0 });
assert.ok(commandMars(landed, 'scan'));
for (let i = 0; i < 110; i++) stepMars(landed, .05);
assert.ok(landed.scan);
Object.assign(landed.rover, { x: 10, z: -15, speed: 0 });
assert.ok(commandMars(landed, 'sample'));
for (let i = 0; i < 110; i++) stepMars(landed, .05);
assert.ok(landed.sample);
assert.equal(commandMars(landed, 'transmit'), false);
commandMars(landed, 'photo', 'data:image/png;base64,test');
commandMars(landed, 'antenna');
assert.equal(commandMars(landed, 'transmit'), false, 'relay position is required');
Object.assign(landed.rover, { x: 0, z: 12, speed: 0 });
assert.ok(communicationReady(landed));
assert.ok(commandMars(landed, 'transmit'));
for (let i = 0; i < 170; i++) stepMars(landed, .05);
assert.equal(landed.phase, 'success');
console.log('PASS: full transfer, safe descent, three failure paths, manual gravity, driving, braking, collision, proximity science, timed operations and complete downlink.');
